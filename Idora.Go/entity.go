package idora

import (
	"errors"
	"reflect"
	"runtime"
)

// Entity is implemented by a type that declares its own prefix. Pass such types to
// [WithEntities] to register them:
//
//	type User struct{ ID string }
//
//	func (User) IDPrefix() string { return "usr" }
//
// IDPrefix is called once, during [New], on a zero value of the type, so it must return a
// constant rather than depend on the receiver's fields. A pointer receiver is fine.
//
// The method must be declared on the type itself. A method promoted from an embedded field is
// rejected with a [*PromotedPrefixError], because prefix declarations are not inherited.
type Entity interface {
	IDPrefix() string
}

const idPrefixMethod = "IDPrefix"

// entityKey reduces a type to the key the registry uses: pointer types are keyed by their
// element type, so *User and User share one prefix. A nil type stays nil.
func entityKey(t reflect.Type) reflect.Type {
	for t != nil && t.Kind() == reflect.Pointer {
		t = t.Elem()
	}
	return t
}

// declaredPrefix returns the registry key and the declared prefix of an Entity value.
func declaredPrefix(e Entity) (reflect.Type, string, error) {
	if e == nil {
		return nil, "", errors.New("idora: WithEntities was given a nil Entity; pass a value of each " +
			"entity type, for example idora.WithEntities(User{})")
	}
	t := entityKey(reflect.TypeOf(e))
	if field, promoted := promotedIDPrefix(t); promoted {
		return t, "", &PromotedPrefixError{EntityType: t, Field: field}
	}
	// *T carries every method of T, so a fresh pointer to a zero value implements Entity whatever
	// the receiver kind, and calling through it never dereferences a nil pointer.
	return t, reflect.New(t).Interface().(Entity).IDPrefix(), nil
}

// promotedIDPrefix reports whether t's IDPrefix method is promoted from an embedded field rather
// than declared on t, and if so names the field.
//
// Go generates a wrapper function for every promoted method, and the runtime reports a wrapper's
// source position as "<autogenerated>"; a method declared on t reports its real file. The
// method to inspect is the one in t's own method set when there is one (a value receiver, or a
// value-receiver method promoted from an embedded field), and otherwise the one in *t's (a
// pointer receiver). *t's copy of a value-receiver method is itself a wrapper, which is why t's
// method set is consulted first.
//
// The position check is confirmed structurally: an IDPrefix can only be promoted if t is a
// struct with an embedded field that provides one. A type with no such field has declared the
// method itself, whatever the runtime says.
func promotedIDPrefix(t reflect.Type) (field string, promoted bool) {
	field, ok := embeddedIDPrefixProvider(t)
	if !ok {
		return "", false
	}
	m, ok := t.MethodByName(idPrefixMethod)
	if !ok {
		m, ok = reflect.PointerTo(t).MethodByName(idPrefixMethod)
	}
	if !ok {
		return "", false
	}
	return field, isAutogenerated(m.Func)
}

// embeddedIDPrefixProvider returns the name of the first embedded field of struct type t whose
// type has an IDPrefix method, through either its value or its pointer method set.
func embeddedIDPrefixProvider(t reflect.Type) (string, bool) {
	if t.Kind() != reflect.Struct {
		return "", false
	}
	for i := range t.NumField() {
		f := t.Field(i)
		if !f.Anonymous {
			continue
		}
		if _, ok := f.Type.MethodByName(idPrefixMethod); ok {
			return f.Name, true
		}
		if k := f.Type.Kind(); k != reflect.Pointer && k != reflect.Interface {
			if _, ok := reflect.PointerTo(f.Type).MethodByName(idPrefixMethod); ok {
				return f.Name, true
			}
		}
	}
	return "", false
}

// isAutogenerated reports whether fn is a compiler-generated wrapper. When the runtime cannot
// say, it answers true: the caller only asks when an embedded field could have supplied the
// method, and refusing an ambiguous declaration is safer than inheriting a prefix.
func isAutogenerated(fn reflect.Value) bool {
	f := runtime.FuncForPC(fn.Pointer())
	if f == nil {
		return true
	}
	file, _ := f.FileLine(f.Entry())
	return file == "<autogenerated>"
}
